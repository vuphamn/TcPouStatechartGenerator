using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;

namespace KvalMachineScope.Xae
{
    /// <summary>
    /// New POUs written into the loaded POU's PLC project (the TcUnit tests made from a recording), as
    /// shared/plcAddFiles.cjs does for the desktop app and VS Code: the files in a folder of the project, each listed in
    /// the .plcproj (its folder too). A file there already is replaced only when MachineScope made it; the test program
    /// (PRG_KssTests) keeps the suites it had. Also whether the project references TcUnit.
    /// </summary>
    public static class PlcAddFiles
    {
        public const string Mark = "generated by Kval MachineScope";

        public sealed class Result
        {
            public bool ok { get; set; }
            public List<string> written { get; set; }
            public bool tcunit { get; set; }
            public string folder { get; set; }
            public string error { get; set; }
            /// <summary>Added in XAE's open project (its tree): saved with XAE's Save All</summary>
            public bool xae { get; set; }
        }

        /// <summary>
        /// The files as they go in: checked (names, a file there already not made by MachineScope refused), the test
        /// program merged with the one there already; null with the error otherwise
        /// </summary>
        public static List<KeyValuePair<string, string>> Prepare(string plcproj, string folder, IList<KeyValuePair<string, string>> files, out string error)
        {
            error = null;
            if (plcproj == null || !File.Exists(plcproj)) { error = "The PLC project (.plcproj) of the POU was not found"; return null; }
            if (folder == null || !Regex.IsMatch(folder, @"^[A-Za-z_][\w ]{0,40}$")) { error = "Not a folder name"; return null; }
            if (files == null || files.Count == 0 || files.Any(f => f.Key == null || f.Value == null || !Regex.IsMatch(f.Key, @"^[A-Za-z_]\w{0,80}\.TcPOU$", RegexOptions.IgnoreCase)))
            {
                error = "Not a POU file";
                return null;
            }
            var dir = Path.Combine(Path.GetDirectoryName(plcproj), folder);
            var output = new List<KeyValuePair<string, string>>();
            foreach (var f in files)
            {
                var full = Path.Combine(dir, f.Key);
                var content = f.Value;
                if (File.Exists(full))
                {
                    var was = File.ReadAllText(full);
                    if (string.Equals(f.Key, "PRG_KssTests.TcPOU", StringComparison.OrdinalIgnoreCase)) content = MergeTestProgram(was, content);
                    else if (!was.Contains(Mark)) { error = folder + "\\" + f.Key + " is there already, not made by MachineScope: not replaced"; return null; }
                }
                output.Add(new KeyValuePair<string, string>(f.Key, content));
            }
            return output;
        }

        public static bool ReferencesTcUnit(string plcproj) => plcproj != null && File.Exists(plcproj) && Regex.IsMatch(File.ReadAllText(plcproj), "Include=\"TcUnit[\",]", RegexOptions.IgnoreCase);

        public static Result Add(string plcproj, string folder, IList<KeyValuePair<string, string>> files)
        {
            if (plcproj == null || !File.Exists(plcproj)) return new Result { ok = false, error = "The PLC project (.plcproj) of the POU was not found" };
            if (folder == null || !Regex.IsMatch(folder, @"^[A-Za-z_][\w ]{0,40}$")) return new Result { ok = false, error = "Not a folder name" };
            if (files == null || files.Count == 0 || files.Any(f => f.Key == null || f.Value == null || !Regex.IsMatch(f.Key, @"^[A-Za-z_]\w{0,80}\.TcPOU$", RegexOptions.IgnoreCase)))
                return new Result { ok = false, error = "Not a POU file" };
            var dir = Path.Combine(Path.GetDirectoryName(plcproj), folder);
            try
            {
                Directory.CreateDirectory(dir);
                var proj = File.ReadAllText(plcproj);
                var before = proj;
                var written = new List<string>();
                foreach (var f in files)
                {
                    var full = Path.Combine(dir, f.Key);
                    var content = f.Value;
                    if (File.Exists(full))
                    {
                        var was = File.ReadAllText(full);
                        if (string.Equals(f.Key, "PRG_KssTests.TcPOU", StringComparison.OrdinalIgnoreCase)) content = MergeTestProgram(was, content);
                        else if (!was.Contains(Mark)) return new Result { ok = false, error = folder + "\\" + f.Key + " is there already, not made by MachineScope: not replaced" };
                    }
                    File.WriteAllText(full, content, new UTF8Encoding(true));
                    written.Add(f.Key);
                    proj = AddToPlcproj(proj, folder + "\\" + f.Key);
                }
                if (proj != before) File.WriteAllText(plcproj, proj, new UTF8Encoding(true));
                return new Result { ok = true, written = written, folder = dir, tcunit = Regex.IsMatch(proj, "Include=\"TcUnit[\",]", RegexOptions.IgnoreCase) };
            }
            catch (Exception ex) when (ex is IOException || ex is UnauthorizedAccessException)
            {
                return new Result { ok = false, error = ex.Message };
            }
        }

        /// <summary>The .plcproj with a file listed to compile (after the last Compile) and its folders</summary>
        public static string AddToPlcproj(string proj, string rel)
        {
            if (Regex.IsMatch(proj, "<Compile\\s+Include=\"" + Regex.Escape(rel) + "\"", RegexOptions.IgnoreCase)) return proj;
            var nl = proj.Contains("\r\n") ? "\r\n" : "\n";
            proj = Regex.Replace(proj, @"<Project(\s[^>]*)?/>", m => "<Project" + m.Groups[1].Value + ">" + nl + "</Project>");
            var compile = "    <Compile Include=\"" + rel + "\">" + nl + "      <SubType>Code</SubType>" + nl + "    </Compile>" + nl;
            var last = Regex.Matches(proj, "<Compile\\s+Include=\"[^\"]*\"\\s*(?:/>|>[\\s\\S]*?</Compile>)\\r?\\n").Cast<Match>().LastOrDefault();
            var output = last != null ? proj.Insert(last.Index + last.Length, compile) : proj.Replace("</Project>", "  <ItemGroup>" + nl + compile + "  </ItemGroup>" + nl + "</Project>");
            var parts = rel.Split('\\');
            for (var i = 1; i < parts.Length; i++)
            {
                var folder = string.Join("\\", parts.Take(i));
                if (Regex.IsMatch(output, "<Folder\\s+Include=\"" + Regex.Escape(folder) + "\"", RegexOptions.IgnoreCase)) continue;
                var line = "    <Folder Include=\"" + folder + "\" />" + nl;
                var lastFolder = Regex.Matches(output, "<Folder\\s+Include=\"[^\"]*\"\\s*/>\\r?\\n").Cast<Match>().LastOrDefault();
                output = lastFolder != null ? output.Insert(lastFolder.Index + lastFolder.Length, line) : output.Replace("</Project>", "  <ItemGroup>" + nl + line + "  </ItemGroup>" + nl + "</Project>");
            }
            return output;
        }

        /// <summary>The test program there already, with the suite instances given added (declared lines "fbX : FB_X;")</summary>
        public static string MergeTestProgram(string existing, string given)
        {
            var declRe = new Regex(@"<Declaration>\s*<!\[CDATA\[([\s\S]*?)\]\]>\s*</Declaration>", RegexOptions.IgnoreCase);
            var suiteRe = new Regex(@"^\s*fb\w+\s*:\s*FB_\w+;\s*$", RegexOptions.IgnoreCase);
            var have = declRe.Match(existing);
            var giv = declRe.Match(given);
            if (!have.Success || !giv.Success) return existing;
            var d = have.Groups[1].Value;
            var haveLines = d.Split('\n').Select(l => l.Trim()).Where(l => suiteRe.IsMatch(l)).ToList();
            var add = giv.Groups[1].Value.Split('\n').Select(l => l.Trim()).Where(l => suiteRe.IsMatch(l) && !haveLines.Any(h => string.Equals(h, l, StringComparison.OrdinalIgnoreCase))).ToList();
            if (add.Count == 0) return existing;
            var nl = d.Contains("\r\n") ? "\r\n" : "\n";
            var varLine = new Regex(@"(\bVAR\b[^\n]*\r?\n)", RegexOptions.IgnoreCase);
            var next = varLine.Replace(d, m => m.Value + string.Concat(add.Select(l => "\t" + l + nl)), 1);
            return existing.Replace(d, next);
        }
    }
}
