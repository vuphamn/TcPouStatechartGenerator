using System.Collections.Generic;
using System.IO;
using KvalMachineScope.Xae;
using Microsoft.VisualStudio.TestTools.UnitTesting;

namespace KvalMachineScope.Xae.Tests
{
    [TestClass]
    public class PlcAddFilesTests
    {
        private const string Proj = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\r\n<Project>\r\n  <ItemGroup>\r\n    <Compile Include=\"POUs\\MAIN.TcPOU\">\r\n      <SubType>Code</SubType>\r\n    </Compile>\r\n  </ItemGroup>\r\n  <ItemGroup>\r\n    <Folder Include=\"POUs\" />\r\n  </ItemGroup>\r\n  <ItemGroup>\r\n    <PlaceholderReference Include=\"TcUnit\">\r\n    </PlaceholderReference>\r\n  </ItemGroup>\r\n</Project>\r\n";

        private static string Prg(params string[] suites) =>
            "<TcPlcObject><POU Name=\"PRG_KssTests\" Id=\"{1}\"><Declaration><![CDATA[PROGRAM PRG_KssTests\r\n// generated by Kval MachineScope\r\nVAR\r\n" + string.Concat(System.Array.ConvertAll(suites, s => "\tfb" + s.Substring(3) + " : " + s + ";\r\n")) + "END_VAR]]></Declaration></POU></TcPlcObject>";

        [TestMethod]
        public void WritesTheFilesAndListsThemInThePlcproj()
        {
            var dir = Path.Combine(Path.GetTempPath(), "kss-addfiles-" + System.Guid.NewGuid().ToString("N"));
            Directory.CreateDirectory(dir);
            var plcproj = Path.Combine(dir, "P.plcproj");
            File.WriteAllText(plcproj, Proj);
            try
            {
                var r = PlcAddFiles.Add(plcproj, "KssTests", new List<KeyValuePair<string, string>>
                {
                    new KeyValuePair<string, string>("FB_A_Test.TcPOU", "<x>// generated by Kval MachineScope</x>"),
                    new KeyValuePair<string, string>("PRG_KssTests.TcPOU", Prg("FB_A_Test")),
                });
                Assert.IsTrue(r.ok, r.error);
                Assert.IsTrue(r.tcunit);
                var proj = File.ReadAllText(plcproj);
                StringAssert.Contains(proj, "<Compile Include=\"KssTests\\FB_A_Test.TcPOU\">");
                StringAssert.Contains(proj, "<Folder Include=\"KssTests\" />");
                // A second suite: the program keeps the first one's instance
                var r2 = PlcAddFiles.Add(plcproj, "KssTests", new List<KeyValuePair<string, string>>
                {
                    new KeyValuePair<string, string>("FB_B_Test.TcPOU", "<x>// generated by Kval MachineScope</x>"),
                    new KeyValuePair<string, string>("PRG_KssTests.TcPOU", Prg("FB_B_Test")),
                });
                Assert.IsTrue(r2.ok, r2.error);
                var prg = File.ReadAllText(Path.Combine(dir, "KssTests", "PRG_KssTests.TcPOU"));
                StringAssert.Contains(prg, "fbA_Test : FB_A_Test;");
                StringAssert.Contains(prg, "fbB_Test : FB_B_Test;");
                // Someone's own file of that name: not replaced
                File.WriteAllText(Path.Combine(dir, "KssTests", "FB_C_Test.TcPOU"), "<mine/>");
                var r3 = PlcAddFiles.Add(plcproj, "KssTests", new List<KeyValuePair<string, string>> { new KeyValuePair<string, string>("FB_C_Test.TcPOU", "<x/>") });
                Assert.IsFalse(r3.ok);
                Assert.AreEqual("<mine/>", File.ReadAllText(Path.Combine(dir, "KssTests", "FB_C_Test.TcPOU")));
                Assert.IsFalse(PlcAddFiles.Add(plcproj, "..\\up", new List<KeyValuePair<string, string>> { new KeyValuePair<string, string>("A.TcPOU", "x") }).ok);
                Assert.IsFalse(PlcAddFiles.Add(plcproj, "KssTests", new List<KeyValuePair<string, string>> { new KeyValuePair<string, string>("..\\A.TcPOU", "x") }).ok);
            }
            finally
            {
                Directory.Delete(dir, true);
            }
        }
    }
}
