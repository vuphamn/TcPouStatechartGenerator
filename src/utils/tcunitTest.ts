/**
 * A TcUnit test from a recorded run (the Live tab's replay): a test suite (EXTENDS TcUnit.FB_TestSuite) whose test
 * drives an instance of the POU through the run: before each step the recorded inputs (the guard values) as they were
 * then, the POU called each cycle until the next recorded state comes; a state not reached within the cycles allowed
 * fails with the step said (AssertEquals_DINT). A starting point: the inputs written must be accessible from outside
 * (VAR_INPUT / public), and a Kval state machine may need its base class enabled first (said in the code).
 */
export interface RecordedRun {
  /** The state values over time (PLC ms) */
  values: { t: number; value: number }[];
  /** The guard variables' values over time: their ids (lower case) */
  vars: { id: string; t: number; v: boolean | number | string | null }[];
  /** id → its symbol on the PLC (instance.path.name) and type */
  watched: Record<string, { symbol?: string; type?: string }>;
  instance?: string;
  started?: number;
}

const ident = (s: string) => s.replace(/[^\w]/g, '_').replace(/^(\d)/, '_$1');
const stLiteral = (v: boolean | number | string) =>
  typeof v === 'boolean' ? (v ? 'TRUE' : 'FALSE') : typeof v === 'number' ? String(v) : `'${String(v).split('$').join('$$').split("'").join("$'")}'`;

/**
 * → { name (the test suite's), code: { declaration, body, method: { name, declaration, code } }, xml (.TcPOU), steps }
 */
export function generateTcUnitTest(o: {
  pou: string;
  enumType: string;
  stateVar: string;
  run: RecordedRun;
  /** A state value's name (its enum member) */
  stateName: (value: number) => string;
  /** At the cycle time (ms) the cycles allowed per step are counted from (default 10 ms) */
  cycleMs?: number;
  title?: string;
  /** Strings written as they are (an enum member, a literal from a guard), not as STRING literals */
  rawStrings?: boolean;
  /** Comments in a step (1-based): what the test cannot set */
  notes?: Record<number, string[]>;
  /** The test method's name before its time (default RecordedRun) */
  methodPrefix?: string;
  /** The suite's name (default FB_<POU>_Test) */
  suiteName?: string;
}): { name: string; xml: string; steps: number; declaration: string; methodName: string; methodCode: string; instance: string } {
  const cycleMs = o.cycleMs ?? 10;
  // The states one after another (the same one twice: once)
  const steps: { t: number; state: string }[] = [];
  for (const s of o.run.values) {
    const state = o.stateName(s.value);
    if (!steps.length || steps[steps.length - 1].state !== state) steps.push({ t: s.t, state });
  }
  // The inputs: each guard variable's symbol relative to the instance (fbUut.<that>)
  const prefix = o.run.instance ? `${o.run.instance}.`.toLowerCase() : '';
  const inputOf = (id: string) => {
    const sym = o.run.watched[id]?.symbol ?? id;
    return sym.toLowerCase().startsWith(prefix) ? sym.slice(prefix.length) : null;
  };
  const valueAt = (id: string, t: number) => {
    let v: boolean | number | string | null | undefined;
    for (const x of o.run.vars) {
      if (x.t > t) break;
      if (x.id === id) v = x.v;
    }
    return v;
  };
  // (not the state variable itself: the run's result, not an input)
  const ids = [...new Set(o.run.vars.map((v) => v.id))].filter((id) => {
    const input = inputOf(id);
    return !!input && input.toLowerCase() !== o.stateVar.toLowerCase();
  });
  const name = ident(o.suiteName ?? `FB_${o.pou.replace(/^FB_/i, '')}_Test`);
  const methodName = ident(`${o.methodPrefix ?? 'RecordedRun'}_${new Date(o.run.started ?? steps[0]?.t ?? Date.now()).toISOString().slice(0, 16).replace(/[-:T]/g, '')}`);
  const n = Math.max(1, steps.length - 1);
  // (each step's cycles allowed: twice its recorded time at the cycle time, at least 100)
  const maxCycles = steps.slice(1).map((s, i) => Math.max(100, Math.ceil(((s.t - steps[i].t) * 2) / cycleMs)));
  const q = (state: string) => `${o.enumType}.${state}`;
  const declaration = [
    `FUNCTION_BLOCK ${name} EXTENDS TcUnit.FB_TestSuite`,
    `// ${o.title ?? 'A recorded run'}: generated by Kval MachineScope; review it before relying on it`,
    'VAR',
    `\tfbUut : ${o.pou};`,
    `\tnStep : INT := 1;`,
    `\tnCycles : UDINT;`,
    '\t// (read by Kval MachineScope while live: 0 running, 1 passed, 2 failed; the step that failed)',
    `\tnResult : INT;`,
    `\tnFailedStep : INT;`,
    `\taExpected : ARRAY[0..${n}] OF ${o.enumType} := [${steps.length ? steps.map((s) => q(s.state)).join(', ') : q('?')}];`,
    `\taMaxCycles : ARRAY[1..${n}] OF UDINT := [${(maxCycles.length ? maxCycles : [100]).join(', ')}];`,
    'END_VAR',
  ].join('\n');
  const arms: string[] = [];
  for (let k = 1; k < steps.length; k++) {
    const writes = ids
      .map((id) => ({ id, v: valueAt(id, steps[k].t), was: valueAt(id, steps[k - 1].t) }))
      .filter((w) => w.v !== null && w.v !== undefined && (k === 1 || w.v !== w.was))
      .map((w) => `\t\tfbUut.${inputOf(w.id)} := ${o.rawStrings && typeof w.v === 'string' ? w.v : stLiteral(w.v as boolean | number | string)};`);
    for (const n of o.notes?.[k] ?? []) writes.push(`\t\t// ${n.replace(/\r?\n/g, ' ')}`);
    arms.push(`\t${k}: // ${steps[k - 1].state} -> ${steps[k].state} (after ${((steps[k].t - steps[k - 1].t) / 1000).toFixed(1)} s recorded)`, ...(writes.length ? writes : ['\t\t;']));
  }
  const methodCode = [
    `TEST('${methodName}: ${steps.length} states recorded');`,
    '// (a Kval state machine: enable it first, as its base class needs, e.g. fbUut.enable())',
    `IF nStep > ${n} THEN`,
    '\tRETURN;',
    'END_IF',
    '// The inputs as recorded before this step',
    'CASE nStep OF',
    ...arms,
    'END_CASE',
    'fbUut();',
    `IF TO_DINT(fbUut.${o.stateVar}) = TO_DINT(aExpected[nStep]) THEN`,
    '\tnStep := nStep + 1;',
    '\tnCycles := 0;',
    'ELSE',
    '\tnCycles := nCycles + 1;',
    'END_IF',
    `IF nStep > ${n} THEN`,
    `\tAssertEquals_DINT(Expected := TO_DINT(aExpected[${n}]), Actual := TO_DINT(fbUut.${o.stateVar}), Message := 'The recorded run: its last state');`,
    '\tnResult := 1;',
    '\tTEST_FINISHED();',
    'ELSIF nCycles > aMaxCycles[nStep] THEN',
    `\tAssertEquals_DINT(Expected := TO_DINT(aExpected[nStep]), Actual := TO_DINT(fbUut.${o.stateVar}), Message := CONCAT('Step ', INT_TO_STRING(nStep)));`,
    '\tnResult := 2;',
    '\tnFailedStep := nStep;',
    `\tnStep := ${n} + 1;`,
    '\tTEST_FINISHED();',
    'END_IF',
  ].join('\n');
  const guid = () => '{xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx}'.replace(/[xy]/g, (c) => { const r = Math.floor(Math.random() * 16); return (c === 'x' ? r : (r & 3) | 8).toString(16); });
  const cdata = (s: string) => `<![CDATA[${s.replace(/\n/g, '\r\n')}]]>`;
  const xml = [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<TcPlcObject Version="1.1.0.1">',
    `  <POU Name="${name}" Id="${guid()}" SpecialFunc="None">`,
    `    <Declaration>${cdata(declaration)}</Declaration>`,
    '    <Implementation>',
    `      <ST>${cdata(`${methodName}();`)}</ST>`,
    '    </Implementation>',
    `    <Method Name="${methodName}" Id="${guid()}">`,
    `      <Declaration>${cdata(`METHOD PRIVATE ${methodName}`)}</Declaration>`,
    '      <Implementation>',
    `        <ST>${cdata(methodCode)}</ST>`,
    '      </Implementation>',
    '    </Method>',
    '  </POU>',
    '</TcPlcObject>',
    '',
  ].join('\r\n');
  return { name, xml, steps: steps.length, declaration, methodName, methodCode, instance: testInstanceName(name) };
}

/** A test suite's instance in the test program: FB_Machine_Test → fbMachine_Test */
export const testInstanceName = (suite: string) => `fb${suite.replace(/^FB_/i, '')}`;
export const TEST_PROGRAM = 'PRG_KssTests';

/**
 * The test program (PRG_KssTests): an instance of each suite, and TcUnit.RUN() (call it from a task of its own, as
 * TcUnit's tests are; a program there already keeps its suites: the host merges them)
 */
export function generateTcUnitProgram(suites: string[]): string {
  const guid = () => '{xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx}'.replace(/[xy]/g, (c) => { const r = Math.floor(Math.random() * 16); return (c === 'x' ? r : (r & 3) | 8).toString(16); });
  const declaration = [`PROGRAM ${TEST_PROGRAM}`, '// The TcUnit tests made from recordings: generated by Kval MachineScope (call it from a task)', 'VAR', ...suites.map((s) => `\t${testInstanceName(s)} : ${s};`), 'END_VAR'].join('\r\n');
  return [
    '<?xml version="1.0" encoding="utf-8"?>',
    '<TcPlcObject Version="1.1.0.1">',
    `  <POU Name="${TEST_PROGRAM}" Id="${guid()}" SpecialFunc="None">`,
    `    <Declaration><![CDATA[${declaration}]]></Declaration>`,
    '    <Implementation>',
    '      <ST><![CDATA[TcUnit.RUN();]]></ST>',
    '    </Implementation>',
    '  </POU>',
    '</TcPlcObject>',
    '',
  ].join('\r\n');
}
