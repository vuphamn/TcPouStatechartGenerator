// New POUs written into a loaded POU's PLC project (the TcUnit tests made from a recording; the desktop app and the
// VS Code extension; the XAE extension does the same in C#): the files in a folder of the project (KssTests), each
// added to the .plcproj (its folder too). A file there already is replaced only when MachineScope made it; the test
// program (PRG_KssTests) keeps the suites it had (their instances merged). Also: whether the project references TcUnit.
const fs = require('fs');
const path = require('path');

const MARK = 'generated by Kval MachineScope';

function nearest(from, ext, levels = 8) {
  let dir = path.dirname(path.resolve(from));
  for (let k = 0; k < levels; k++) {
    try {
      const hit = fs.readdirSync(dir).find((n) => n.toLowerCase().endsWith(ext));
      if (hit) return path.join(dir, hit);
    } catch {
      return null;
    }
    const up = path.dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
  return null;
}

/** A .plcproj with a file (its path from the project's folder) listed to compile, and its folders */
function addToPlcproj(proj, relPath) {
  const rel = relPath.replace(/\//g, '\\');
  if (new RegExp(`<Compile\\s+Include="${rel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"`, 'i').test(proj)) return proj;
  const nl = proj.includes('\r\n') ? '\r\n' : '\n';
  // (an empty project written <Project/>: opened, its items put in)
  proj = proj.replace(/<Project(\s[^>]*)?\/>/, (m, attrs = '') => `<Project${attrs}>${nl}</Project>`);
  const compile = `    <Compile Include="${rel}">${nl}      <SubType>Code</SubType>${nl}    </Compile>${nl}`;
  // (after the last Compile; else in a new ItemGroup before </Project>)
  const lastCompile = [...proj.matchAll(/<Compile\s+Include="[^"]*"\s*(?:\/>|>[\s\S]*?<\/Compile>)\r?\n/g)].pop();
  let out = lastCompile ? proj.slice(0, lastCompile.index + lastCompile[0].length) + compile + proj.slice(lastCompile.index + lastCompile[0].length) : proj.replace(/<\/Project>/, `  <ItemGroup>${nl}${compile}  </ItemGroup>${nl}</Project>`);
  // Its folders (each level), when not listed
  const parts = rel.split('\\').slice(0, -1);
  for (let i = 1; i <= parts.length; i++) {
    const folder = parts.slice(0, i).join('\\');
    if (new RegExp(`<Folder\\s+Include="${folder.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}"`, 'i').test(out)) continue;
    const lastFolder = [...out.matchAll(/<Folder\s+Include="[^"]*"\s*\/>\r?\n/g)].pop();
    const line = `    <Folder Include="${folder}" />${nl}`;
    out = lastFolder ? out.slice(0, lastFolder.index + lastFolder[0].length) + line + out.slice(lastFolder.index + lastFolder[0].length) : out.replace(/<\/Project>/, `  <ItemGroup>${nl}${line}  </ItemGroup>${nl}</Project>`);
  }
  return out;
}

/** The test program as given, with the suite instances the one there already had (declared lines `fbX : FB_X_Test;`) */
function mergeTestProgram(existing, given) {
  const decl = (xml) => /<Declaration>\s*<!\[CDATA\[([\s\S]*?)\]\]>\s*<\/Declaration>/i.exec(xml)?.[1] ?? '';
  const suites = (d) => d.split(/\r?\n/).filter((l) => /^\s*fb\w+\s*:\s*FB_\w+;\s*$/i.test(l)).map((l) => l.trim());
  const have = suites(decl(existing));
  const add = suites(decl(given)).filter((l) => !have.some((h) => h.toLowerCase() === l.toLowerCase()));
  if (!add.length) return existing;
  const d = decl(existing);
  const nl = d.includes('\r\n') ? '\r\n' : '\n';
  const next = d.replace(/(\bVAR\b[^\n]*\r?\n)/i, (m) => m + add.map((l) => `\t${l}${nl}`).join(''));
  return existing.replace(d, next);
}

/**
 * The files ([{ name, content }], .TcPOU) into <the PLC project>/<folder>/, listed in the .plcproj →
 * { ok, written: [names], plcproj, tcunit } or { ok: false, error }
 */
function addPlcFiles(pouPath, req) {
  if (typeof pouPath !== 'string' || !path.isAbsolute(pouPath)) return { ok: false, error: 'No PLC project loaded' };
  const plcproj = nearest(pouPath, '.plcproj');
  if (!plcproj) return { ok: false, error: 'The PLC project (.plcproj) of the POU was not found' };
  const folder = String(req?.folder ?? '');
  const files = Array.isArray(req?.files) ? req.files : [];
  if (!/^[A-Za-z_][\w ]{0,40}$/.test(folder)) return { ok: false, error: 'Not a folder name' };
  if (!files.length || files.some((f) => !/^[A-Za-z_]\w{0,80}\.TcPOU$/i.test(String(f?.name)) || typeof f?.content !== 'string')) return { ok: false, error: 'Not a POU file' };
  const dir = path.join(path.dirname(plcproj), folder);
  try {
    fs.mkdirSync(dir, { recursive: true });
    let proj = fs.readFileSync(plcproj, 'utf8');
    const before = proj;
    const written = [];
    for (const f of files) {
      const full = path.join(dir, f.name);
      let content = f.content;
      if (fs.existsSync(full)) {
        const was = fs.readFileSync(full, 'utf8');
        if (/^PRG_KssTests\.TcPOU$/i.test(f.name)) content = mergeTestProgram(was, content);
        else if (!was.includes(MARK)) return { ok: false, error: `${folder}\\${f.name} is there already, not made by MachineScope: not replaced` };
      }
      fs.writeFileSync(full, content);
      written.push(f.name);
      proj = addToPlcproj(proj, `${folder}\\${f.name}`);
    }
    if (proj !== before) fs.writeFileSync(plcproj, proj);
    return { ok: true, written, plcproj, folder: dir, tcunit: /Include="TcUnit[",]/i.test(proj) };
  } catch (err) {
    return { ok: false, error: err.message };
  }
}

module.exports = { addPlcFiles, addToPlcproj, mergeTestProgram, MARK };
