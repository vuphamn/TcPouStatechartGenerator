// Writes src/styles/appThemes.css: the app's light themes (the Theme selector: default, base, neutral, forest; dark is
// Tailwind's own palette). Tailwind 4's colours are CSS variables (--color-<name>-<shade>), so a theme redefines them
// on :root[data-app-theme=…]: each palette's scale turned around (950 <-> 50, 900 <-> 100, …, the middle kept), so the
// app's dark-on-light classes read as light-on-dark ones did. The greys (slate) per theme: slate, zinc, neutral, or a
// green-tinted slate (forest). The colours src/index.css writes as hex: --kss-<hex> (see SHEET). Run:
// node scripts/gen-app-themes.cjs
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const theme = fs.readFileSync(path.join(root, 'node_modules', 'tailwindcss', 'theme.css'), 'utf8');
const colors = {};
for (const m of theme.matchAll(/--color-([a-z]+)-(\d+):\s*([^;]+);/g)) (colors[m[1]] ??= {})[m[2]] = m[3].trim();

// The shade each one takes in a light theme (the middle ones kept: buttons, accents)
const LIGHT = { 50: 950, 100: 900, 200: 800, 300: 700, 400: 600, 500: 500, 600: 600, 700: 300, 800: 200, 900: 100, 950: 50 };
// (forest: slate's lightness, a green hue, a little more colour in the pale shades)
const tint = (v, hue) => v.replace(/oklch\(\s*([\d.]+%?)\s+([\d.]+)\s+([\d.]+)\s*\)/, (_, l, c) => `oklch(${l} ${Math.max(Number(c), 0.03).toFixed(3)} ${hue})`);

const block = (name, greys) => {
  const lines = [`:root[data-app-theme='${name}'] {`, '  color-scheme: light;'];
  for (const [palette, shades] of Object.entries(colors)) {
    const src = palette === 'slate' ? greys : shades;
    for (const shade of Object.keys(shades)) {
      const to = src[LIGHT[shade]] ?? src[shade];
      if (to) lines.push(`  --color-${palette}-${shade}: ${to};`);
    }
  }
  // (text-white: the emphasis on dark backgrounds, dark here; on a coloured button still readable)
  lines.push(`  --color-white: ${greys[950] ?? colors.slate[950]};`);
  lines.push(...sheetVars(true));
  lines.push('}');
  return lines.join('\n');
};

// The colours written in src/index.css (hex, as Tailwind 3 had them): each a variable, its hex in the dark theme,
// in a light one the shade it stands for (turned around with the palette); the scrollbar's track too
const SHEET = {
  '38bdf8': 'sky-400', '7dd3fc': 'sky-300', '0284c7': 'sky-600', '0369a1': 'sky-700', '0c4a6e': 'sky-900',
  f59e0b: 'amber-500', fbbf24: 'amber-400', fef3c7: 'amber-100',
  '34d399': 'emerald-400', '10b981': 'emerald-500', '059669': 'emerald-600', '6ee7b7': 'emerald-300', a7f3d0: 'emerald-200', d1fae5: 'emerald-100', '064e3b': 'emerald-900',
  '818cf8': 'indigo-400', e0e7ff: 'indigo-100', '312e81': 'indigo-900',
  fb923c: 'orange-400', f97316: 'orange-500', facc15: 'yellow-400', a78bfa: 'violet-400', c084fc: 'purple-400',
  '22c55e': 'green-500', '4ade80': 'green-400', a3e635: 'lime-400', '2dd4bf': 'teal-400', '60a5fa': 'blue-400',
  f87171: 'red-400', ef4444: 'red-500', fb7185: 'rose-400',
  '94a3b8': 'slate-400', '64748b': 'slate-500', e2e8f0: 'slate-200', '334155': 'slate-700', '1e293b': 'slate-800', '090d16': 'slate-950',
};
const sheetVars = (light) => Object.entries(SHEET).map(([hex, c]) => `  --kss-${hex}: ${light ? `var(--color-${c})` : `#${hex}`};`);
const forest = Object.fromEntries(Object.entries(colors.slate).map(([k, v]) => [k, tint(v, 155)]));
const out = [
  '/* Generated by scripts/gen-app-themes.cjs: the app\'s light themes (Tailwind\'s palette turned around). Do not edit. */',
  [':root {', ...sheetVars(false), '}'].join('\n'),
  block('default', colors.slate),
  block('base', colors.zinc ?? colors.slate),
  block('neutral', colors.neutral ?? colors.slate),
  block('forest', forest),
  '',
].join('\n\n');
fs.mkdirSync(path.join(root, 'src', 'styles'), { recursive: true });
fs.writeFileSync(path.join(root, 'src', 'styles', 'appThemes.css'), out);
console.log(`src/styles/appThemes.css: ${Object.keys(colors).length} palettes, 4 themes`);
